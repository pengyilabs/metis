/* ============ QUIZ ============ */
function startQuiz() {
  quizState.current = 0;
  quizState.answers = [null,null,null,null,null];
  quizState.flagged = [false,false,false,false,false];
  quizState.timeLeft = 25*60;
  if (quizState.timer) clearInterval(quizState.timer);
  quizState.timer = setInterval(function() {
    quizState.timeLeft--;
    if (quizState.timeLeft <= 0) {
      clearInterval(quizState.timer);
      submitQuiz();
      return;
    }
    var m = Math.floor(quizState.timeLeft / 60), s = quizState.timeLeft % 60;
    var el = document.getElementById('timeLeft');
    if (el) el.textContent = (m<10?'0':'') + m + ':' + (s<10?'0':'') + s;
  }, 1000);
  renderQuiz();
  var panel = document.getElementById('aiPanel');
  if (panel && !panel.dataset.greeted) {
    panel.dataset.greeted = '1';
    setTimeout(function() {
      toggleAiPanel();
      addAiTyping(function() { addAiMsg(t('ai_greeting'), 'ai'); });
    }, 800);
  }
}

function renderQuiz() {
  var box = document.getElementById('quizBox');
  var side = document.getElementById('quizSidebar');
  if (!box || !side) return;
  var q = quizQuestions[quizState.current];
  var opts = '';
  q.opts.forEach(function(o, i) {
    var sel = quizState.answers[quizState.current] === i ? ' selected' : '';
    opts += '<div class="quiz-option' + sel + '" onclick="selectOption(' + i + ')">' +
      '<div class="quiz-opt-letter">' + String.fromCharCode(65+i) + '</div><div>' + t(o) + '</div></div>';
  });
  var m = Math.floor(quizState.timeLeft / 60), s = quizState.timeLeft % 60;
  var timeStr = (m<10?'0':'') + m + ':' + (s<10?'0':'') + s;
  box.innerHTML =
    '<div class="quiz-meta"><span class="quiz-label">' + t('question') + ' ' + (quizState.current+1) + '</span><span class="quiz-points">' + t('points') + '</span></div>' +
    '<div class="question-text">' + t(q.key) + '</div>' +
    '<div class="quiz-options">' + opts + '</div>' +
    '<div class="quiz-nav">' +
    '<button class="btn btn-outline" onclick="quizNav(-1)"' + (quizState.current===0?' disabled':'') + '>' + t('prev') + '</button>' +
    '<label class="flag-label"><input type="checkbox" ' + (quizState.flagged[quizState.current]?'checked':'') + ' onchange="toggleFlag(this.checked)"> ' + t('flagged') + '</label>' +
    '<button class="btn btn-primary" onclick="quizNav(1)">' + (quizState.current===quizQuestions.length-1 ? t('finish_attempt') : t('next')) + '</button></div>';

  side.innerHTML =
    '<div class="qblock"><div class="qblock-title">' + t('time_left') + '</div><div class="time-left" id="timeLeft">' + timeStr + '</div></div>' +
    '<div class="qblock"><div class="qblock-title">' + t('quiz_nav') + '</div>' +
    '<div class="nav-grid">' + quizQuestions.map(function(_, i) {
      var cls = 'nav-sq';
      if (quizState.answers[i] !== null) cls += ' answered';
      if (i === quizState.current) cls += ' current';
      if (quizState.flagged[i]) cls += ' flagged';
      return '<div class="' + cls + '" onclick="quizGoto(' + i + ')">' + (i+1) + '</div>';
    }).join('') + '</div>' +
    '<button class="finish-link" onclick="showPage(\'quiz-summary\')">' + t('finish_attempt') + '</button></div>';
}

function selectOption(i) {
  quizState.answers[quizState.current] = i;
  renderQuiz();
}
function toggleFlag(v) {
  quizState.flagged[quizState.current] = v;
  renderQuiz();
}
function quizNav(dir) {
  if (dir === 1 && quizState.current === quizQuestions.length - 1) {
    showPage('quiz-summary');
    return;
  }
  quizState.current = Math.max(0, Math.min(quizQuestions.length - 1, quizState.current + dir));
  renderQuiz();
}
function quizGoto(i) {
  quizState.current = i;
  renderQuiz();
}

function renderSummary() {
  var tbl = document.getElementById('summaryTable');
  if (!tbl) return;
  var rows = quizQuestions.map(function(_, i) {
    var st = quizState.answers[i] !== null ? t('answered') : t('unanswered');
    var stCls = quizState.answers[i] !== null ? 'status-answered' : 'status-unanswered';
    var fl = quizState.flagged[i] ? '<span class="status-dot status-flagged"></span>' : '';
    return '<tr><td>' + t('question') + ' ' + (i+1) + '</td><td><span class="status-dot ' + stCls + '"></span>' + st + '</td><td>' + fl + '</td></tr>';
  }).join('');
  tbl.innerHTML = '<thead><tr><th>' + t('sum_q') + '</th><th>' + t('sum_status') + '</th><th>' + t('sum_flag') + '</th></tr></thead><tbody>' + rows + '</tbody>';
}

function submitQuiz() {
  if (quizState.timer) clearInterval(quizState.timer);
  alert(t('toast_submitted'));
  showPage('course');
}

/* ============ STUDENT AI PANEL ============ */
function toggleAiPanel() {
  var p = document.getElementById('aiPanel');
  p.classList.toggle('open');
  if (p.classList.contains('open')) {
    document.getElementById('aiInput').focus();
  }
}

function addAiTyping(cb) {
  var c = document.getElementById('aiMessages');
  var typing = document.createElement('div');
  typing.className = 'ai-typing';
  typing.innerHTML = '<span></span><span></span><span></span>';
  c.appendChild(typing);
  c.scrollTop = c.scrollHeight;
  setTimeout(function() {
    if (typing.parentNode) typing.parentNode.removeChild(typing);
    if (cb) cb();
  }, 1200);
}

function addAiMsg(text, who) {
  var c = document.getElementById('aiMessages');
  var msg = document.createElement('div');
  msg.className = 'ai-msg ' + who;
  msg.textContent = text;
  c.appendChild(msg);
  c.scrollTop = c.scrollHeight;
}

function sendAiMessage() {
  var input = document.getElementById('aiInput');
  var msg = input.value.trim();
  if (!msg) return;
  addAiMsg(msg, 'user');
  input.value = '';
  addAiTyping(function() {
    var hints = [t('ai_hint1'), t('ai_hint2'), t('ai_hint3'), t('ai_hint4'), t('ai_hint5')];
    var r = msg.length < 12 ? t('ai_fallback') : hints[Math.floor(Math.random() * hints.length)];
    addAiMsg(r, 'ai');
    if (Math.random() > 0.5) {
      setTimeout(function() { addAiMsg(t('ai_keeper'), 'ai'); }, 600);
    }
  });
}

/* ============ EDUCATOR AI PANEL ============ */
var pendingInsert = null;

function toggleEditorAi() {
  var p = document.getElementById('editorAiPanel');
  p.classList.toggle('open');
  if (p.classList.contains('open') && !p.dataset.greeted) {
    p.dataset.greeted = '1';
    addEditorAiMsg(t('ai_gen_intro'), 'ai');
    addEditorAiMsg(genActionsHtml(), 'ai', true);
  }
}

function genActionsHtml() {
  return '<div class="gen-actions"><button class="btn btn-primary btn-sm" onclick="generateQuiz()">' + t('ai_quiz') + '</button><button class="btn btn-outline btn-sm" onclick="generateHomework()">' + t('ai_hw') + '</button></div>';
}

function openEditorAi(sectionIdx) {
  pendingInsert = sectionIdx;
  var p = document.getElementById('editorAiPanel');
  if (!p.classList.contains('open')) toggleEditorAi();
  document.getElementById('editorAiInput').focus();
}

function addEditorAiTyping(cb) {
  var c = document.getElementById('editorAiMessages');
  var typing = document.createElement('div');
  typing.className = 'ai-typing';
  typing.innerHTML = '<span></span><span></span><span></span>';
  c.appendChild(typing);
  c.scrollTop = c.scrollHeight;
  setTimeout(function() {
    if (typing.parentNode) typing.parentNode.removeChild(typing);
    if (cb) cb();
  }, 1500);
}

function addEditorAiMsg(text, who, isHtml) {
  var c = document.getElementById('editorAiMessages');
  var msg = document.createElement('div');
  msg.className = 'editor-ai-msg ' + who;
  if (isHtml) msg.innerHTML = text; else msg.textContent = text;
  c.appendChild(msg);
  c.scrollTop = c.scrollHeight;
}

function generateQuiz() {
  addEditorAiMsg(t('ai_quiz'), 'user');
  addEditorAiTyping(function() {
    var html = '<div>' + t('ai_gen_outline_quiz').replace(/\n/g, '<br>') + '</div>' +
      '<button class="insert-btn" onclick="insertActivity(\'quiz\')">' + t('ai_gen_insert') + '</button>';
    addEditorAiMsg(html, 'ai', true);
  });
}

function generateHomework() {
  addEditorAiMsg(t('ai_hw'), 'user');
  addEditorAiTyping(function() {
    var html = '<div>' + t('ai_gen_outline_hw').replace(/\n/g, '<br>') + '</div>' +
      '<button class="insert-btn" onclick="insertActivity(\'assign\')">' + t('ai_gen_insert') + '</button>';
    addEditorAiMsg(html, 'ai', true);
  });
}

function insertActivity(type) {
  var si = pendingInsert !== null ? pendingInsert : 0;
  var name = type === 'quiz' ? 'ai_gen_quiz_name' : 'ai_gen_hw_name';
  var desc = type === 'quiz' ? 'ai_gen_quiz_desc' : 'ai_gen_hw_desc';
  courseSections[si].activities.push({ type: type, name: name, desc: desc, done: false });
  courseSections[si].open = true;
  renderCourse();
  addEditorAiMsg(t('ai_gen_done'), 'ai');
  setTimeout(function() {
    var el = document.getElementById('section-' + si);
    if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }, 100);
}

function sendEditorAiMessage() {
  var input = document.getElementById('editorAiInput');
  var msg = input.value.trim();
  if (!msg) return;
  addEditorAiMsg(msg, 'user');
  input.value = '';
  addEditorAiTyping(function() {
    addEditorAiMsg(t('ai_gen_intro'), 'ai');
    addEditorAiMsg(genActionsHtml(), 'ai', true);
  });
}

