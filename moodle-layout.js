function showPage(id) {
  pages.forEach(function(p) {
    var el = document.getElementById('page-' + p);
    if (el) el.classList.toggle('active', p === id);
  });
  document.querySelectorAll('.leftnav-item').forEach(function(a) {
    a.classList.toggle('active', a.getAttribute('data-page') === id);
  });
  window.location.hash = id;
  var fab = document.getElementById('aiFab');
  var panel = document.getElementById('aiPanel');
  if (id === 'quiz') {
    fab.classList.remove('hidden');
  } else {
    fab.classList.add('hidden');
    panel.classList.remove('open');
  }
  if (id === 'course') renderCourse();
  if (id === 'dashboard') renderDashboard();
  if (id === 'materials') renderMaterials();
  if (id === 'quiz') startQuiz();
  if (id === 'quiz-summary') renderSummary();
  closeAllMenus();
}

/* ============ DASHBOARD ============ */
function renderDashboard() {
  var grid = document.getElementById('courseGrid');
  if (!grid) return;
  grid.innerHTML = '';
  courses.forEach(function(c) {
    var card = document.createElement('div');
    card.className = 'course-card';
    card.onclick = function() { showPage('course'); };
    card.innerHTML =
      '<div class="course-header"><h3>' + t(c.key) + '</h3></div>' +
      '<div class="course-body">' + t(c.desc) +
      '<div class="course-meta"><span>' + c.students + ' ' + t('course_students') + '</span><span>' + t('course_progress') + ': ' + c.progress + '%</span></div></div>';
    grid.appendChild(card);
  });
}

