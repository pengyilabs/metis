var currentLang = localStorage.getItem('metis-lang') || 'en';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('metis-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('.lang-option').forEach(function(el) {
    el.classList.toggle('active', el.getAttribute('data-lang') === lang);
  });
  var aiIn = document.getElementById('aiInput');
  if (aiIn) aiIn.placeholder = t('ai_input_ph');
  var edIn = document.getElementById('editorAiInput');
  if (edIn) edIn.placeholder = t('ai_teacher_ph');
  renderDashboard();
  renderCourse();
  renderMaterials();
  if (document.getElementById('page-quiz').classList.contains('active')) renderQuiz();
  if (document.getElementById('page-quiz-summary').classList.contains('active')) renderSummary();
  closeAllMenus();
}

