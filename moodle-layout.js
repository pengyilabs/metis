function showCourseTab(tab) {
  courseTab = tab;
  document.querySelectorAll('.tab-btn').forEach(function(b) {
    b.classList.toggle('active', b.getAttribute('data-tab') === tab);
  });
  renderCourse();
}

function renderCourse() {
  var main = document.getElementById('courseMain');
  var index = document.getElementById('courseIndex');
  if (!main || !index) return;
  document.querySelectorAll('.tab-btn').forEach(function(b) {
    b.classList.toggle('active', b.getAttribute('data-tab') === courseTab);
  });
  index.innerHTML = '<div style="font-weight:700;font-size:14px;padding:8px 10px 12px">' + t('course_index') + '</div>';

  // build course index (always the sections tree)
  courseSections.forEach(function(sec, si) {
    var ci = document.createElement('div');
    ci.className = 'ci-section' + (sec.open ? ' open' : '');
    ci.innerHTML = '<div class="ci-header" onclick="toggleSection(' + si + ')">' +
      '<svg class="ci-chevron" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="9 18 15 12 9 6"/></svg>' +
      t('topic') + ' ' + sec.id + '</div>' +
      '<div class="ci-items">' + sec.activities.map(function(a, ai) {
        var ic = iconFor(a.type);
        return '<div class="ci-item" onclick="goActivity(' + si + ',' + ai + ')"><span class="ci-dot" style="background:' + ic.color + '"></span>' + t(a.name) + '</div>';
      }).join('') + '</div>';
    index.appendChild(ci);
  });

  main.innerHTML = '';
  if (courseTab === 'participants') return renderStubParticipants(main);
  if (courseTab === 'grades') return renderStubGrades(main);
  if (courseTab === 'reports') return renderStubReports(main);
  if (courseTab === 'more') return renderStubMore(main);

  courseSections.forEach(function(sec, si) {
    var activitiesHtml = sec.activities.map(function(a, ai) {
      var ic = iconFor(a.type);
      return '<div class="activity-row" onclick="if(\'' + a.type + '\'===\'quiz\')showPage(\'quiz\')">' +
        '<div class="activity-icon" style="background:' + ic.color + '">' + ic.icon + '</div>' +
        '<div class="activity-info"><div class="activity-title">' + t(a.name) + '</div><div class="activity-desc">' + t(a.desc) + '</div></div>' +
        '<div class="activity-status"><span class="pill' + (a.done ? ' done' : '') + '">' + (a.done ? t('status_done') : t('status_todo')) + '</span></div></div>';
    }).join('');
    var addHtml = editMode
      ? '<div class="add-activity" onclick="openEditorAi(' + si + ')"><svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><line x1="12" y1="5" x2="12" y2="19"/><line x1="5" y1="12" x2="19" y2="12"/></svg> ' + t('add_activity') + '</div>'
      : '';
    var card = document.createElement('div');
    card.className = 'section-card' + (sec.open ? ' open' : '');
    card.id = 'section-' + si;
    card.innerHTML =
      '<div class="sec-header" onclick="toggleSection(' + si + ')"><h3>' + t('topic') + ' ' + sec.id + '</h3>' +
      '<svg class="sec-toggle" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="6 9 12 15 18 9"/></svg></div>' +
      '<div class="' + (sec.open ? 'sec-body' : 'sec-body collapsed') + '">' + activitiesHtml + addHtml + '</div>';
    main.appendChild(card);
  });
  document.getElementById('aiSparkleBtn').style.display = editMode ? 'flex' : 'none';
}

